#!/usr/bin/env sh
# First deployment of RDIC CRM with Docker Compose.
#
#   sh deploy/first-deploy.sh            # app on port 7060 (RD_PORT in .env)
#
# - Creates .env with generated secrets when it does not exist yet.
# - Creates empty runtime-config files that are missing (review them later).
# - Builds, migrates, seeds one administrator, runs the production preflight
#   and starts every service.
# Safe to re-run: existing .env, config files, data and users are kept.
# Use deploy/update.sh for later releases.
# Only port 7060 is published, so 80/443 and other services stay untouched.
set -eu

ROOT_DIR=$(CDPATH= cd -- "$(dirname -- "$0")/.." && pwd)
cd "$ROOT_DIR"

for command_name in docker; do
  command -v "$command_name" >/dev/null 2>&1 || {
    echo "Missing required command: $command_name" >&2
    exit 2
  }
done
docker compose version >/dev/null 2>&1 || { echo "Docker Compose v2 is required" >&2; exit 2; }

random_hex() {
  od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'
}

release=$(tr -d '[:space:]' < VERSION)
if git rev-parse --short=12 HEAD >/dev/null 2>&1; then
  revision=$(git rev-parse --short=12 HEAD)
else
  revision="manual-$(date -u +%Y%m%d%H%M%S)"
fi

if [ ! -f .env ]; then
  postgres_password=$(random_hex 24)
  umask 077
  cat > .env <<EOF
# Generated by deploy/first-deploy.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Never commit this file.
POSTGRES_PASSWORD=$postgres_password
RD_DATABASE_URL=postgresql+psycopg://rdic:$postgres_password@database:5432/rdic
RD_SECRET_KEY=$(random_hex 32)
# Host port for the app. Only this port is used on the server.
RD_PORT=7060
# false = direct http://server-ip:7060 access. Set true once HTTPS is in front.
RD_COOKIE_SECURE=false
RD_IMAGE=rdic-crm:$release
RD_RELEASE=$release
RD_REVISION=$revision
# Balance API credentials (ask the client).
RD_SUBSCRIPTION_KEY=
RD_PRIVATE_KEY_PATH=/app/secrets/private_key.pem
RD_PRIVATE_KEY_PASSWORD=
# Initial administrator, seeded only when no user exists.
# TEMPORARY: change this password from the Users page right after the first login.
RD_ADMIN_USERNAME=admin
RD_ADMIN_DISPLAY_NAME=Administrator
RD_ADMIN_PASSWORD=admin
EOF
  umask 022
  echo "Created .env with generated database password and secret key."
fi

configured_release=$(sed -n 's/^RD_RELEASE=//p' .env | tail -n 1 | tr -d '\r')
test "$release" = "$configured_release" || {
  echo "VERSION ($release) and .env RD_RELEASE ($configured_release) differ" >&2
  exit 2
}

mkdir -p runtime-config secrets
seed_config() {
  if [ ! -f "runtime-config/$1" ]; then
    printf '%s\n' "$2" > "runtime-config/$1"
    echo "Created placeholder runtime-config/$1 (review before go-live)."
  fi
}
if [ ! -f runtime-config/import_config.json ]; then
  cp config.example.json runtime-config/import_config.json
  echo "Created runtime-config/import_config.json from config.example.json."
  echo "  -> Set the real Balance API base_url before go-live."
fi
seed_config client_data_overrides.json '{"version": 1, "clients": []}'
seed_config client_identity_groups.json '{"version": 2, "groups": []}'
seed_config ignored_clients.json '{"version": 1, "names": []}'
seed_config client_profile_enrichment.json '{"version": 1, "source": "initial deployment", "allowed_products": ["CCA", "CCB", "LB"], "records": []}'
seed_config supplier_directory.json '{"version": 1, "suppliers": []}'

docker compose config --quiet
docker compose build --pull
docker compose up -d database
docker compose run --rm migrate
docker compose run --rm migrate \
  python -m rd_web.admin bootstrap-admin --if-missing --allow-weak-password
docker compose run --rm --no-deps migrate python -m rd_ops preflight --production
docker compose up -d --remove-orphans

attempt=0
until docker compose exec -T web python -c \
  "import urllib.request; urllib.request.urlopen('http://127.0.0.1:8000/health/ready', timeout=5)" \
  >/dev/null 2>&1; do
  attempt=$((attempt + 1))
  if [ "$attempt" -ge 24 ]; then
    echo "Web service did not become ready. Inspect: docker compose logs web scheduler" >&2
    exit 3
  fi
  sleep 5
done

docker compose ps
port=$(sed -n 's/^RD_PORT=//p' .env | tail -n 1 | tr -d '\r')
admin_user=$(sed -n 's/^RD_ADMIN_USERNAME=//p' .env | tail -n 1 | tr -d '\r')
echo
echo "RDIC CRM $release ($revision) is running on port ${port:-7060}: http://<server-ip>:${port:-7060}"
echo "Sign in as '$admin_user'. If the seed password is still the temporary one,"
echo "change it from the Users page now, then clear RD_ADMIN_PASSWORD in .env."
